// Builds the two shipped artifacts at the repo root (jsDelivr serves from there):
//   extractor.js  - IIFE for JavaScriptCore (ejs solver + our parsers)
//   po_token.html - self-contained BotGuard page for WKWebView
import { build } from 'esbuild';
import fs from 'node:fs';

const ejsLib = fs.readFileSync('vendor/ejs/yt.solver.lib.min.js', 'utf8');
const ejsCore = fs.readFileSync('vendor/ejs/yt.solver.core.min.js', 'utf8');

const ext = await build({
  entryPoints: ['src/extractor/index.js'],
  bundle: true, format: 'iife', target: 'es2020', write: false, legalComments: 'none',
});
const extractor = [
  '// tonik-rules extractor. Generated by build.mjs - do not edit.',
  '// Bundles yt-dlp/ejs (Unlicense), meriyah (ISC) and astring (MIT).',
  '(function(globalThis){',
  ejsLib,
  ';var meriyah=lib.meriyah,astring=lib.astring;',
  ejsCore,
  ';globalThis.__tonikSolver=jsc;',
  ext.outputFiles[0].text,
  '})(typeof globalThis!=="undefined"?globalThis:this);',
].join('\n');
fs.writeFileSync('extractor.js', extractor);

if (fs.existsSync('src/po_token/page.js')) {
  const page = await build({
    entryPoints: ['src/po_token/page.js'],
    bundle: true, format: 'iife', target: 'es2020', write: false, legalComments: 'none', minify: true,
  });
  const html = fs.readFileSync('src/po_token/template.html', 'utf8').replace('/*__SCRIPT__*/', () => page.outputFiles[0].text);
  fs.writeFileSync('po_token.html', html);
}
console.log('built extractor.js', extractor.length, 'bytes');
